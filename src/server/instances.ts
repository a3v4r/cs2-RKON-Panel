import { execFile, spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { dataDir } from './accounts';
import { chatCfgLines } from './chat-log';
import { ensureMetamod, ensureRussian } from './cs2-files';
import { isUpdating } from './cs2-update';
import { cs2Paths } from './panel-settings';
import { rconCommand } from './rcon';
import { StoredServer, servers } from './store';

// Runs CS2 servers on this PC the way the tournament kit's start-server.ps1 did:
// one CS2 install, a generated cfg per server, Metamod in gameinfo.gi, restart after a crash.
// Servers are started detached, so they keep running when the panel stops; on the next start the
// panel finds them again by the PIDs saved in data/processes.json.

export type ProcState = 'stopped' | 'starting' | 'running' | 'stopping' | 'crashed';

interface Proc {
  state: ProcState;
  pid?: number;
  startedAt?: number;
  message?: string;
  stopRequested?: boolean;
  restartTimer?: NodeJS.Timeout;
}

const WATCH_MS = 3_000;
const MIN_UPTIME_FOR_RESTART_MS = 60_000; // a crash right after start would only loop
const RESTART_DELAY_MS = 5_000;
const STOP_WAIT_MS = 10_000;
// 0xC000013A: the server console window was closed (or Ctrl+C) - a manual stop, not a crash
const CONSOLE_CLOSED = [3221225786, -1073741510];

const g = globalThis as unknown as { instProcs?: Map<number, Proc>; instWatcher?: NodeJS.Timeout };
const procs = (g.instProcs ??= new Map<number, Proc>());

const pidFile = () => path.join(dataDir(), 'processes.json');

function savePids() {
  const running: Record<number, { pid: number; startedAt: number }> = {};
  for (const [id, p] of procs) {
    if (p.pid && p.startedAt && (p.state === 'running' || p.state === 'stopping')) running[id] = { pid: p.pid, startedAt: p.startedAt };
  }
  try {
    fs.mkdirSync(dataDir(), { recursive: true });
    fs.writeFileSync(pidFile(), JSON.stringify(running, null, 2));
  } catch {
    // losing the file only means the panel will not re-attach after its own restart
  }
}

function alive(pid: number) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (e) {
    return (e as NodeJS.ErrnoException).code === 'EPERM';
  }
}

// A saved PID may belong to another program by now: only adopt it if it is still a cs2.exe
function isCs2(pid: number): Promise<boolean> {
  return new Promise((resolve) => {
    execFile('tasklist', ['/FI', `PID eq ${pid}`, '/FO', 'CSV', '/NH'], { windowsHide: true }, (err, out) => {
      resolve(!err && /"cs2\.exe"/i.test(out));
    });
  });
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

export function procState(id: number) {
  const p = procs.get(id);
  return { state: p?.state ?? 'stopped', message: p?.message, startedAt: p?.startedAt };
}

export function allStates() {
  const result: Record<number, ReturnType<typeof procState>> = {};
  for (const s of servers.list()) if (s.managed) result[s.id] = procState(s.id);
  return result;
}

const cfgName = (id: number) => `matchdesk_server${id}.cfg`;
const cfgValue = (v: string) => v.replace(/["\r\n]/g, '');

async function writeCfg(csgo: string, server: StoredServer) {
  const m = server.managed!;
  const cfg = [
    '// Generated by Matchdesk on every start - edits here are overwritten',
    `hostname "${cfgValue(server.name)}"`,
    `rcon_password "${cfgValue(server.rcon_password)}"`,
    `sv_password "${cfgValue(m.password)}"`,
    'sv_lan 1',
    'sv_hibernate_when_empty 0',
    'tv_enable 1',
    // In-game chat goes to the panel's Chat section
    ...(await chatCfgLines(server)),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(csgo, 'cfg', cfgName(server.id)), cfg);
}

function onExit(id: number, proc: Proc, code: number | null) {
  if (procs.get(id) !== proc) return; // already handled (exit event and watcher both report)
  const uptime = Date.now() - (proc.startedAt ?? Date.now());  if (proc.stopRequested || (code !== null && CONSOLE_CLOSED.includes(code))) {
    procs.set(id, { state: 'stopped', message: proc.stopRequested ? undefined : 'Окно консоли сервера закрыли вручную' });
    savePids();
    return;
  }
  const codeText = code === null ? '' : ` (код ${code})`;
  const server = servers.get(id);
  if (server?.managed?.autoRestart && uptime >= MIN_UPTIME_FOR_RESTART_MS) {
    const next: Proc = { state: 'starting', message: `Сервер упал${codeText}, перезапуск через 5 секунд` };
    next.restartTimer = setTimeout(() => {
      if (procs.get(id) !== next) return;
      startServer(id).catch((e) => procs.set(id, { state: 'crashed', message: (e as Error).message }));
    }, RESTART_DELAY_MS);
    procs.set(id, next);
  } else {
    procs.set(id, {
      state: 'crashed',
      message: uptime < MIN_UPTIME_FOR_RESTART_MS
        ? `Сервер упал сразу после запуска${codeText}. Посмотрите окно консоли сервера и логи addons\\counterstrikesharp\\logs.`
        : `Сервер остановился${codeText}`,
    });
  }
  savePids();
}

export async function startServer(id: number) {
  const server = servers.get(id);
  if (!server?.managed) throw new Error('Этот сервер запускается не из панели');
  const current = procs.get(id);
  if (current?.state === 'running' || current?.state === 'stopping') return;
  if (current?.restartTimer) clearTimeout(current.restartTimer);
  if (isUpdating()) throw new Error('Идёт обновление CS2: запустите сервер, когда оно закончится');

  const paths = cs2Paths();
  if (!fs.existsSync(paths.exe)) {
    throw new Error(`Не найден ${paths.exe}. Укажите папку сервера CS2 в настройках панели.`);
  }
  ensureMetamod(paths.gameinfo);
  ensureRussian(paths.csgo);
  await writeCfg(paths.csgo, server);

  const m = server.managed;
  const args = [
    '-dedicated', '-console', '-usercon',
    // Without -ip CS2 binds RCON (TCP) to one interface of its choice, sometimes a VPN adapter
    '-ip', m.bindIp || '0.0.0.0',
    '-port', String(server.port),
    '-maxplayers', String(m.maxPlayers),
    '+tv_port', String(m.tvPort),
    '+game_type', '0', '+game_mode', '1',
    '+map', m.map,
    '+exec', cfgName(id),
  ];
  const pid = await launch(paths.exe, args);
  const proc: Proc = { state: 'running', pid, startedAt: Date.now() };
  procs.set(id, proc);
  waitForExit(id, proc);
  savePids();
}

const psQuote = (s: string) => `'${s.replace(/'/g, "''")}'`;

// cs2.exe is started through PowerShell's Start-Process (as the kit did), so it is not a child of the panel:
// stopping or restarting the panel, even with its whole process tree, leaves running matches alone.
// All arguments are validated numbers, map names and IPs, so joining them with spaces is safe.
function launch(exe: string, args: string[]): Promise<number> {
  const command = `$p = Start-Process -FilePath ${psQuote(exe)} -ArgumentList ${psQuote(args.join(' '))} -WorkingDirectory ${psQuote(path.dirname(exe))} -PassThru; $p.Id`;
  return new Promise((resolve, reject) => {
    execFile('powershell', ['-NoProfile', '-NonInteractive', '-Command', command], { windowsHide: true, timeout: 30_000 }, (err, out, stderr) => {
      const pid = Number(String(out).trim());
      if (err || !pid) reject(new Error(`Не удалось запустить cs2.exe: ${(stderr || err?.message || 'нет PID').toString().trim()}`));
      else resolve(pid);
    });
  });
}

// A small PowerShell waits for the server process and returns its exit code: closing the server window by hand
// (0xC000013A) must not count as a crash. It dies with the panel; the panel starts a new one when it re-attaches.
function waitForExit(id: number, proc: Proc) {
  if (!proc.pid) return;
  const command = `$p = Get-Process -Id ${proc.pid} -ErrorAction Stop; $null = $p.Handle; $p.WaitForExit(); exit $p.ExitCode`;
  const waiter = spawn('powershell', ['-NoProfile', '-NonInteractive', '-Command', command], { windowsHide: true, stdio: 'ignore' });
  waiter.on('exit', (code) => {
    if (proc.pid && alive(proc.pid)) return; // the waiter itself failed; the watcher still keeps an eye on the server
    onExit(id, proc, code);
  });
  waiter.on('error', () => {});
}

export async function stopServer(id: number) {
  const proc = procs.get(id);
  if (!proc) return;
  if (proc.restartTimer) clearTimeout(proc.restartTimer);
  if (!proc.pid || !alive(proc.pid)) {
    procs.set(id, { state: 'stopped' });
    savePids();
    return;
  }
  proc.stopRequested = true;
  proc.state = 'stopping';
  const pid = proc.pid;

  // Ask the server to quit by itself first, then end the process
  const server = servers.get(id);
  if (server) await rconCommand('127.0.0.1', server.port, server.rcon_password, 'quit').catch(() => {});
  for (let waited = 0; waited < STOP_WAIT_MS && alive(pid); waited += 500) await sleep(500);
  if (alive(pid)) {
    await new Promise((resolve) => execFile('taskkill', ['/PID', String(pid), '/T', '/F'], { windowsHide: true }, resolve));
    for (let waited = 0; waited < 3000 && alive(pid); waited += 250) await sleep(250);
  }
  onExit(id, proc, null);
}

export async function restartServer(id: number) {
  await stopServer(id);
  await startServer(id);
}

function watch() {
  for (const [id, proc] of procs) {
    if ((proc.state === 'running' || proc.state === 'stopping') && proc.pid && !alive(proc.pid)) onExit(id, proc, null);
  }
}

// Called once when the panel starts: re-attach to servers that kept running, then keep an eye on them
export async function startInstanceWatcher() {
  if (g.instWatcher) return;
  g.instWatcher = setInterval(watch, WATCH_MS);
  let saved: Record<string, { pid: number; startedAt: number }> = {};
  try {
    saved = JSON.parse(fs.readFileSync(pidFile(), 'utf8'));
  } catch {
    return;
  }
  for (const [key, { pid, startedAt }] of Object.entries(saved)) {
    const id = Number(key);
    if (procs.has(id) || !servers.get(id)?.managed) continue;
    if (alive(pid) && (await isCs2(pid))) {
      const proc: Proc = { state: 'running', pid, startedAt };
      procs.set(id, proc);
      waitForExit(id, proc);
    }
  }
  savePids();
}

export const isRunning = (id: number) => {
  const state = procs.get(id)?.state;
  return state === 'running' || state === 'starting' || state === 'stopping';
};
